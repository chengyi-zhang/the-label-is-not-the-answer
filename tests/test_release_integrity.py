from __future__ import annotations

import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TEXT_SUFFIXES = {".py", ".md", ".txt", ".json", ".csv", ".toml", ".cff", ".yml", ".yaml"}
CASE_LEVEL_TERMS = re.compile(
    r"\bcase_id\b|\boriginal_case_id\b|\bselected_ids\b|\bimage_path\b|"
    r"\breasoning_trace\b|\braw_output\b|\bqualitative_case_ids\b",
    re.I,
)
FORBIDDEN = {
    "machine_path": re.compile(r"(?:[A-Za-z]:\\Users\\|/(?:root|home)/)", re.I),
    "cloud_host": re.compile(r"seetacloud|connect\.westd", re.I),
    "private_platform": re.compile(r"\bAutoDL\b|\bIsambard\b", re.I),
    "email_address": re.compile(r"[\w.+-]+@[\w.-]+\.[A-Za-z]{2,}"),
    "private_key": re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
    "common_secret": re.compile(
        r"(?:sk-|hf_|ghp_|github_pat_|xox[baprs]-)[A-Za-z0-9_-]{12,}|"
        r"AKIA[0-9A-Z]{16}|AIza[0-9A-Za-z_-]{30,}"
    ),
    "credential_url": re.compile(r"https?://[^\s]+(?:auth_key|access_token|signature|token)=", re.I),
    "legacy_condition": re.compile(
        r"\bv[2][-_]?a[1][0]\b|\bv[1]_baseline\b|\blabel[_-]?neutr[a]l\b|\bprompt[_-]?only\b",
        re.I,
    ),
    "development_team_name": re.compile(r"perfect[-_ ]?wave", re.I),
}


def main() -> None:
    assert not (ROOT / ".git").exists(), "release package must not contain repository history"
    required = [
        "README.md",
        "LICENSE",
        "NOTICE",
        "CITATION.cff",
        "configs/experiment_manifest.json",
        "figures/figure1.pdf",
        "figures/figure1_preview.png",
        "results/canonical/primary_summary.csv",
        "results/canonical/replication_and_scale.json",
        "results/anchor_intervention/qwen2_5_vl_3b.json",
    ]
    for relative in required:
        assert (ROOT / relative).is_file(), f"missing required file: {relative}"

    for path in ROOT.rglob("*"):
        if not path.is_file() or ".git" in path.parts:
            continue
        assert "__pycache__" not in path.parts and path.suffix != ".pyc", f"generated bytecode: {path}"
        assert path.stat().st_size < 10 * 1024 * 1024, f"unexpected large file: {path}"
        assert path.name not in {
            "raw.jsonl",
            "results.json",
            ".env",
            ".netrc",
        }, f"private artefact: {path}"
        assert path.suffix.lower() not in {".pem", ".p12", ".key", ".log"}, f"private artefact: {path}"
        if path.suffix == ".json":
            json.loads(path.read_text(encoding="utf-8"))
        if path.suffix in TEXT_SUFFIXES and path != Path(__file__).resolve():
            text = path.read_text(encoding="utf-8", errors="replace")
            for name, pattern in FORBIDDEN.items():
                assert not pattern.search(text), f"{name} found in {path.relative_to(ROOT)}"
            if path.is_relative_to(ROOT / "results") or path.is_relative_to(ROOT / "figures" / "data"):
                assert not CASE_LEVEL_TERMS.search(text), f"case-level material found in {path.relative_to(ROOT)}"

        if path.suffix.lower() in {".pdf", ".png"}:
            payload = path.read_bytes()
            binary_forbidden = {
                b"C:\\Users\\",
                b"/root/",
                b"/home/",
                b"seetacloud",
                b"connect.westd",
                b"@swansea",
                b"@aston",
                b"@columbia",
            }
            for marker in binary_forbidden:
                assert marker.lower() not in payload.lower(), f"binary metadata leak in {path.relative_to(ROOT)}"

    print("Release integrity checks passed.")


if __name__ == "__main__":
    main()
